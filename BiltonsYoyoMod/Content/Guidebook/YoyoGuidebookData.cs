		public static string BookTitle(string bookId)
		{
			return bookId switch {
				"General" => "Yoyo Guidebook: General",
				"Yoyos" => "Yoyo Guidebook: Yoyos",
				"Accessories" => "Yoyo Guidebook: Accessories",
				"Others" => "Yoyo Guidebook: Others",
				"Consumables" => "Yoyo Guidebook: Consumables",
				"BlocksBosses" => "Yoyo Guidebook: Blocks & Bosses",
				_ => "Yoyo Guidebook",
			};
		}

